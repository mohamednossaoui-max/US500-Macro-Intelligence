def to_float(value):
    if value is None:
        return None

    try:
        if isinstance(value, str):
            value = value.strip()

        if value == "":
            return None

        return float(value)

    except (TypeError, ValueError):
        return None


def calculate_pct_change(
    start_price,
    end_price
):
    """
    Percentage change from event reference close
    to future trading-session close.
    """

    if start_price is None:
        return None

    if end_price is None:
        return None

    if start_price == 0:
        return None

    return (
        (end_price - start_price)
        / start_price
        * 100.0
    )


def classify_reaction(
    reaction_pct
):
    """
    Descriptive classification only.

    NOT a trading signal.
    """

    if reaction_pct is None:
        return "UNKNOWN"

    if reaction_pct >= 2.0:
        return "STRONG_POSITIVE"

    if reaction_pct > 0.25:
        return "POSITIVE"

    if reaction_pct >= -0.25:
        return "NEUTRAL"

    if reaction_pct > -2.0:
        return "NEGATIVE"

    return "STRONG_NEGATIVE"


