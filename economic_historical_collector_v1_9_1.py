def make_record_id(row):
    raw = "|".join(str(row[c]) for c in ["indicator","agency","release_date","release_time","reference_period","source_url"])
    return hashlib.sha256(raw.encode()).hexdigest()[:16]

def main():
    df = pd.DataFrame(RECORDS)
    df = df.drop_duplicates(subset=["indicator","agency","release_date","release_time","reference_period","source_url"], keep="first")
    quality=[]
    for _, r in df.iterrows():
        issues=[]; safe=True
        if pd.isna(r["release_date"]) or pd.isna(r["vintage_date"]):
            safe=False; issues.append("missing_release_or_vintage_date")
        elif pd.to_datetime(r["vintage_date"]) > pd.to_datetime(r["release_date"]):
            safe=False; issues.append("vintage_after_release")
        if pd.isna(r["actual"]):
            safe=False; issues.append("missing_actual")
        if pd.isna(r["source_url"]) or not str(r["source_url"]).strip():
            safe=False; issues.append("missing_source_url")
        quality.append({"record_id":make_record_id(r),"indicator":r["indicator"],"agency":r["agency"],"release_date":r["release_date"],"reference_period":r["reference_period"],"point_in_time_safe":safe,"quality_issues":"; ".join(issues),"historical_consensus_available":bool(pd.notna(r["consensus"]) and str(r["consensus_source"]).strip() not in ("","nan","None"))})
    q=pd.DataFrame(quality)
    df=df.sort_values(["release_date","indicator"]).reset_index(drop=True)
    df.to_csv(OUTPUT_EVENTS,index=False); q.to_csv(OUTPUT_QUALITY,index=False)
